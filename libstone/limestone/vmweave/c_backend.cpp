Result<std::string> emit_c(const Module& input) {
  auto checked=checked_module(input); if(!checked) return Result<std::string>::err(checked.error());
  auto parts=fragments(checked.value()); std::string c=header(checked.value());
  for(const auto& name:component_names()) if(parts.contains(name)) c+="\n/* ."+name+" */\n"+parts.at(name);
  return Result<std::string>::ok(std::move(c));
}
