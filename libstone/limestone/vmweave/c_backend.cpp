std::map<std::string,std::string> fragments(const Module& m) {
  const auto& s=m.configuration; std::map<std::string,std::string> out;
  for(const auto& c:s.components) {
    std::string body;
    if(c=="insncode") body=handlers(m);
    else if(c=="srtbl" || c=="addrtbl" || c=="insntbl") body=table(m,c);
    else if(c=="dispatch") body=dispatch(m);
    else if(c=="compile") body=compiler(m);
    else if(c=="rewrite") body=rewriting(m);
    else if(c=="opcode") {
      for(const auto& w:m.words) body+="#define "+s.name+"_opcode_"+w.name+" "+std::to_string(w.opcode)+"u\n";
    } else if(c=="token") {
      body="const char *"+s.name+"_token(uint32_t opcode) { const "+s.name+"_metadata *info="+s.name+"_lookup(opcode); return info ? info->name : NULL; }\n";
    } else body=optional(m,c);
    if(auto it=s.subsystem_c.find(c);it!=s.subsystem_c.end()) body+="\n/* User subsystem extension. */\n"+it->second+"\n";
    out[c]=body;
  }
  return out;
}
