#!/usr/bin/env python3
"""Regenerate domchain/domas/encode/domas_symas_banks.inc.

Embeds every `.dsymspec` databank from domlibs/domsymas/compiler/stdspec as a
SymAS JSON document compiled by DomAS at runtime (via domsymascc_core). The
specs are evaluated with the same DSL used by domsymascc; this script shells
out to a Lua interpreter (the repository's DomMune subset is Lua 5.4 compatible
for the restricted DSL) and writes a C++ header.

Usage:
    python3 scripts/generate_domas_symas_banks.py
"""
import glob
import os
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STDSPEC = os.path.join(REPO, "domlibs", "domsymas", "compiler", "stdspec")
OUT = os.path.join(REPO, "domchain", "domas", "encode", "domas_symas_banks.inc")
LUA = os.environ.get("LUA", "lua")


def main() -> int:
    specs = sorted(glob.glob(os.path.join(STDSPEC, "*.dsymspec")))
    banks = []
    for spec in specs:
        arch = os.path.splitext(os.path.basename(spec))[0]
        proc = subprocess.run(
            [LUA, spec], cwd=STDSPEC, capture_output=True, text=True
        )
        if proc.returncode != 0:
            sys.stderr.write("error: %s: %s\n" % (arch, proc.stderr.strip()))
            return 1
        doc = proc.stdout.strip()
        if ")JSON\"" in doc:
            sys.stderr.write("error: %s: JSON contains raw-string delimiter\n" % arch)
            return 1
        banks.append((arch, doc))

    lines = [
        "// Generated by scripts/generate_domas_symas_banks.py — do not edit.",
        "// Embedded SymAS JSON documents (one per architecture), produced from",
        "// domlibs/domsymas/compiler/stdspec/*.dsymspec. Loaded by DomAS as its",
        "// primary instruction/encoding databank via domsymascc_core.",
        "",
        "#ifndef DOMAS_SYMAS_BANKS_INC",
        "#define DOMAS_SYMAS_BANKS_INC",
        "",
        "struct domas_symas_bank_entry {",
        "    const char *arch;",
        "    const char *json;",
        "};",
        "",
        "static const domas_symas_bank_entry kDomasSymAsBanks[] = {",
    ]
    for arch, doc in banks:
        lines.append('    { "%s", R"JSON(%s)JSON" },' % (arch, doc))
    lines.append("};")
    lines.append("")
    lines.append("static const unsigned kDomasSymAsBankCount = %d;" % len(banks))
    lines.append("")
    lines.append("#endif /* DOMAS_SYMAS_BANKS_INC */")
    lines.append("")

    with open(OUT, "w") as f:
        f.write("\n".join(lines))
    print("wrote %d databanks to %s" % (len(banks), OUT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
